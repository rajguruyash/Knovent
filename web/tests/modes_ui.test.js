// ---------------------------------------------------------------- who answered
const EX = (o) => ({ path: "pipeline", mode: "deterministic", provider: null, model: null, generated_by: "deterministic", failure_kind: null, ...o });

test("who answered is said from the record only, and a local model is never claimed for a provider's answer", () => {
  const p = page();
  const say = (o) => p.run("whoAnswered(" + JSON.stringify(EX(o)) + ")");
  const cloud = [say({ mode: "platform", provider: "openrouter", model: "qwen/qwen3.5-9b", generated_by: "model" }), say({ mode: "byok", provider: "openai", model: "gpt-x", generated_by: "model" }), say({ mode: "byok", provider: "openai_compatible", generated_by: "model" })];
  for (const t of cloud) assert.ok(!/your own computer|stayed on your computer|local/i.test(t) && /third party/.test(t) && /checked against your knowledge/.test(t), t);
  assert.match(cloud[0], /OpenRouter.*platform ai/i);
  const local = say({ mode: "local", provider: "ollama", model: "qwen3:4b", generated_by: "model" });
  assert.match(local, /model on your own computer.*Ollama.*qwen3:4b.*evidence stayed on your computer/s);
  assert.ok(!/third party|sent to/i.test(local), local);
  for (const g of ["deterministic", "deterministic_no_consent"]) assert.match(say({ generated_by: g, failure_kind: "consent:missing_or_revoked" }), /Nothing was sent to any AI provider/);
  for (const mode of ["platform", "byok", "local"]) {
    const fb = say({ mode, provider: mode === "local" ? "ollama" : "openrouter", generated_by: "deterministic_fallback", failure_kind: "provider:server" });
    assert.match(fb, /not a model’s answer/); assert.match(fb, /not handed to any other provider/); assert.ok(!/model on your own computer/.test(fb), fb);
  }
  assert.match(say({ generated_by: "deterministic_fallback", failure_kind: "limit:quota_requests", mode: "platform" }), /monthly request limit is reached/);
  assert.match(say({ generated_by: "unavailable", failure_kind: "provider:timeout", mode: "byok" }), /chose not to fall back/);
  assert.equal(p.run("whoAnswered(null)"), null);
});

